/** 대사의 {…} 를 동물에 맞게 바꾼다 */
export const fillLine = (text: string, a: CallAnimal) =>
  text.replace(/\{(e|name|me|food|foodName|did|go)\}/g, (_, k: keyof CallAnimal) => String(a[k]))

export interface CallPlan { hello: string; topics: CallTopic[]; bye: string }
/** 한 통화: 인사 → 이야기 3개(이 동물만의 이야기 1개는 꼭) → 끝인사. 대사는 이미 바꿔 둔다 */
export function planCall(animal: number, rnd: () => number = Math.random): CallPlan {
  const a = CALL_ANIMALS[animal]
  const pickFrom = <T,>(list: T[]) => list.splice(Math.floor(rnd() * list.length), 1)[0]
  const own = [...a.topics]
  const first = pickFrom(own)
  const rest = [...own, ...SHARED_TOPICS]
  const chosen = [first, pickFrom(rest), pickFrom(rest)]
  // 동물만의 이야기가 늘 맨 앞이면 뻔하니 순서를 섞는다
  for (let i = chosen.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [chosen[i], chosen[j]] = [chosen[j], chosen[i]] }
  const fillTopic = (tp: CallTopic): CallTopic => ({ ask: fillLine(tp.ask, a), replies: tp.replies.map((r) => ({ label: fillLine(r.label, a), answer: fillLine(r.answer, a) })) })
  return { hello: fillLine(pickFrom([...HELLOS]), a), topics: chosen.map(fillTopic), bye: fillLine(pickFrom([...BYES]), a) }
}
